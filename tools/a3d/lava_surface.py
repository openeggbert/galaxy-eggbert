#!/usr/bin/env python3
"""Writes src/GalaxyEggbert/Game/LavaSurfaceData.hpp: the lava's wave, frame by frame, from the
original Amapi sources speedyblupi-data/originals/Decor/lave/lave-1..5.a3d (read only).

Each frame's "Form1" is a slab whose top is a height field on an 11 x 6 grid (x across 4 m, z
across 2 m). The tiles object-m.png 68-72 are those frames in order, seen from the slab's far
side (x mirrored): their silhouettes match the frames' front profiles best that way (correlation
0.82, 0.91, 0.66, 0.53, 0.48; tools/a3d/README in plans/audit/a3d_format.md). Heights map to a
fraction of a cell by the least-squares fit of the profiles to the silhouettes:
    frac = A * h_inches + B   (mean error 0.026 of a cell)
The grid is written mirrored in x so it reads as the tiles do; its border is set to the
trough level so neighbouring lava cells join without a step.

Usage: python3 tools/a3d/lava_surface.py [--data ../speedyblupi-data] [--check]
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import a3d  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "src", "GalaxyEggbert", "Game", "LavaSurfaceData.hpp")
A, B = 0.00336, 0.1468
TROUGH_INCHES = 31.5


def frame_grid(path):
    shape = [s for s in a3d.read(path) if s.name == "Form1"][0]
    tops = [v for v in shape.vertices if v[1] > 0.5]
    xs = sorted({round(v[0], 1) for v in tops})
    zs = sorted({round(v[2], 1) for v in tops})
    return tops, xs, zs


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--data", default=os.path.join(REPO, "..", "speedyblupi-data"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    base = os.path.join(args.data, "originals", "Decor", "lave")
    _, xs0, zs0 = frame_grid(os.path.join(base, "lave-1.a3d"))
    frames = []
    for k in range(1, 6):
        tops, _, _ = frame_grid(os.path.join(base, "lave-%d.a3d" % k))
        grid = []
        for z in zs0:
            row = []
            for x in reversed(xs0):  # mirrored in x, as the tiles show it
                nearest = min(tops, key=lambda v: (v[0] - x) ** 2 + (v[2] - z) ** 2)
                row.append(A * nearest[1] + B)
            grid.append(row)
        trough = A * TROUGH_INCHES + B
        nz, nx = len(grid), len(grid[0])
        for iz in range(nz):
            for ix in range(nx):
                if iz in (0, nz - 1) or ix in (0, nx - 1):
                    grid[iz][ix] = trough
        frames.append(grid)
    nz, nx = len(frames[0]), len(frames[0][0])
    lines = [
        "#pragma once",
        "",
        "// Generated by tools/a3d/lava_surface.py from the original Amapi sources",
        "// speedyblupi-data/originals/Decor/lave/lave-1..5.a3d (\"Form1\", the slab's height-field top).",
        "// Do not edit: rerun the tool. Heights are fractions of a cell (frac = %.5f * inches + %.4f, the" % (A, B),
        "// least-squares fit of the frames' profiles to the tiles object-m.png 68-72); x mirrored as the",
        "// tiles show it; the border at the trough level so lava cells join.",
        "",
        "namespace GalaxyEggbert::Game",
        "{",
        "    inline constexpr int kLavaFrames = 5;",
        "    inline constexpr int kLavaGridX = %d;" % nx,
        "    inline constexpr int kLavaGridZ = %d;" % nz,
        "    inline constexpr float kLavaRimHeight = %.4ff;" % (A * TROUGH_INCHES + B),
        "    inline constexpr float kLavaHeights[kLavaFrames][kLavaGridZ][kLavaGridX] = {",
    ]
    for grid in frames:
        lines.append("        {")
        for row in grid:
            lines.append("            {" + ", ".join("%.4ff" % h for h in row) + "},")
        lines.append("        },")
    lines += ["    };", "}", ""]
    text = "\n".join(lines)
    if args.check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        return 0 if current == text else 1
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s (%d frames, %d x %d)" % (OUT, len(frames), nx, nz))
    return 0


if __name__ == "__main__":
    sys.exit(main())
