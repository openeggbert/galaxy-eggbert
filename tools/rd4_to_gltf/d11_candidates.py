#!/usr/bin/env python3
"""Candidates for D11 (models that look wrong): the object models that differ most from their sprites.

Reads a library built by build_object_library.py with the current objects.txt (each model's
``icons.txt`` silhouette IoU per icon and its ``compare.png``: sprite, model, overlap), ranks the
models by their worst icon's IoU and by their colour error against the sprites
(calibrate_tone.error), and writes the markdown table and a contact sheet of the leading ones
(per model: its worst icon's sprite above the model).

    python3 tools/rd4_to_gltf/build_object_library.py --originals ../speedyblupi-data/originals \\
        --sheets ../mobile-eggbert/Content/icons --objects tools/rd4_to_gltf/objects.txt \\
        --out build-probe/rd4-objects-current
    python3 tools/rd4_to_gltf/d11_candidates.py build-probe/rd4-objects-current \\
        --md plans/inventory/d11_candidates.md --sheet build-probe/d11-candidates.png
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

sys.path.insert(0, str(Path(__file__).resolve().parent))

import calibrate_tone as ct  # noqa: E402

IOU_FLAG = 0.85
COLOUR_FLAG = 20.0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("library", type=Path)
    ap.add_argument("--md", type=Path, required=True)
    ap.add_argument("--sheet", type=Path, required=True)
    ap.add_argument("--count", type=int, default=16)
    args = ap.parse_args(argv)
    rows = []
    for d in sorted(p for p in args.library.iterdir() if (p / "icons.txt").exists() and (p / "compare.png").exists()):
        icons = [line.split() for line in (d / "icons.txt").read_text().splitlines() if line.startswith("icon ")]
        if not icons:
            continue
        ious = [float(f[6]) for f in icons]
        worst = int(np.argmin(ious))
        px = ct.sheet_pixels(d / "compare.png")
        colour = ct.error(*px) if px is not None else float("nan")
        # Badness: how far below the silhouette flag, plus how far above the colour flag (scaled).
        score = max(0.0, IOU_FLAG - min(ious)) * 100 + max(0.0, colour - COLOUR_FLAG)
        rows.append((score, d.name, min(ious), float(np.mean(ious)), colour, worst, len(icons)))
    rows.sort(reverse=True)
    lead = rows[:args.count]

    lines = ["# D11 candidates: the object models that differ most from their sprites", "",
             "Generated by `tools/rd4_to_gltf/d11_candidates.py` from a full object library build (its docstring has",
             "the commands). For the owner to confirm or replace with their own list (D11 in",
             "`plans/GALAXY_EGGBERT_COMPLETION.md`). Silhouette: IoU of the model against each sprite icon (worst, mean);",
             f"colour: mean colour error against the sprites (0-255 scale). Flagged: worst IoU below {IOU_FLAG} or colour",
             f"error above {COLOUR_FLAG:g}. Known and recorded: the bird's and the plants' low IoU is thin wings, legs and",
             "leaves a pixel off (faithful); the fish's head is BB3D-032.", "",
             "| Rank | Model | Icons | IoU worst | IoU mean | Colour error | Flag |", "|---|---|---|---|---|---|---|"]
    for k, (score, name, worst, mean, colour, _w, n) in enumerate(lead, start=1):
        flags = [f for f, on in (("silhouette", worst < IOU_FLAG), ("colour", colour > COLOUR_FLAG)) if on]
        lines.append(f"| {k} | {name} | {n} | {worst:.3f} | {mean:.3f} | {colour:.1f} | {', '.join(flags) or '-'} |")
    lines += ["", f"{len(rows)} models ranked; {sum(1 for r in rows if r[0] > 0)} flagged."]
    args.md.write_text("\n".join(lines) + "\n")

    cell = 160
    sheet = Image.new("RGB", (cell * 4, (cell * 2 + 20) * ((len(lead) + 3) // 4)), (30, 30, 30))
    draw = ImageDraw.Draw(sheet)
    for k, (_s, name, worst, _m, colour, w, n) in enumerate(lead):
        im = Image.open(args.library / name / "compare.png").convert("RGB")
        h = im.height // 3
        cw = im.width // n
        col = im.crop((w * cw, 0, (w + 1) * cw, 2 * h)).resize((cell, cell * 2))
        x, y = (k % 4) * cell, (k // 4) * (cell * 2 + 20)
        sheet.paste(col, (x, y + 20))
        draw.text((x + 4, y + 4), f"{k + 1}. {name[:22]}", fill=(255, 255, 255))
    args.sheet.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(args.sheet)
    print(f"{len(rows)} models; wrote {args.md} and {args.sheet}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
