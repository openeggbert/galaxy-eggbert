#!/usr/bin/env python3
"""Writes plans/inventory/assets.md: one row per converted 3D model, from the shipped files.

For every model under avatars3d/ (Blupi, his vehicles, the objects listed in
avatars3d/objects/index.txt): the Ray Dream source scene and camera (the model's icons.txt header,
or tools/rd4_to_gltf/objects.txt), its parts, its clips, the sprite icons it replaces and how well
its poses cover them (IoU, min and mean), and where the game loads it. The models are generated by
tools/rd4_to_gltf/ (do not edit them by hand); rerun this after regenerating them.

    python3 tools/asset_inventory.py            # writes plans/inventory/assets.md
    python3 tools/asset_inventory.py --check    # fails if the file is stale
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AVATARS = ROOT / "avatars3d"
OUT = ROOT / "plans" / "inventory" / "assets.md"


def objects_sources() -> dict:
    """name -> (sheet, icons, scenes) from tools/rd4_to_gltf/objects.txt."""
    table = {}
    for line in (ROOT / "tools" / "rd4_to_gltf" / "objects.txt").read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split()
        if len(fields) >= 4:
            table.setdefault(fields[0], []).append((fields[1], fields[2], fields[3]))
    return table


def model_row(directory: Path, sources: dict) -> dict:
    parts = sorted(directory.glob("*.verts.bin"))
    clips = sorted((directory / "clips").glob("*.clip.bin")) if (directory / "clips").is_dir() else []
    icons_file = directory / "icons.txt"
    source, icons, ious = "", [], []
    if icons_file.exists():
        for line in icons_file.read_text(encoding="utf-8").splitlines():
            if line.startswith("# ") and not source and ":" in line and "generated by" in line:
                source = line[2:].split(";")[0].split(":", 1)[1].strip()
            fields = line.split()
            if fields and fields[0] == "icon" and len(fields) >= 7:
                icons.append(f"{fields[1]}:{fields[2]}")
                ious.append(float(fields[6]))
    name = directory.name.split("_", 1)[0]
    if not source and name in sources:
        source = "; ".join(scene for _, _, scene in sources[name])
    return {
        "dir": directory.relative_to(ROOT).as_posix(),
        "source": source or "(see the directory's README)",
        "parts": len(parts),
        "clips": len(clips),
        "icons": icons,
        "iou": (min(ious), sum(ious) / len(ious)) if ious else None,
    }


def icon_summary(icons: list) -> str:
    if not icons:
        return "-"
    by_sheet: dict = {}
    for item in icons:
        sheet, icon = item.split(":")
        by_sheet.setdefault(sheet, []).append(int(icon))
    out = []
    for sheet, numbers in by_sheet.items():
        numbers = sorted(set(numbers))
        runs, start, prev = [], numbers[0], numbers[0]
        for n in numbers[1:] + [None]:
            if n is not None and n == prev + 1:
                prev = n
                continue
            runs.append(f"{start}" if start == prev else f"{start}-{prev}")
            if n is not None:
                start = prev = n
        out.append(f"{sheet} {','.join(runs)}")
    return "; ".join(out)


def build() -> str:
    sources = objects_sources()
    lines = [
        "# 3D asset inventory",
        "",
        "Generated by `tools/asset_inventory.py` from the shipped models (do not edit by hand). One row",
        "per converted model: its Ray Dream source in `../speedyblupi-data/originals` (GPLv3, © Daniel Roux",
        "& EPSITEC SA), its parts and clips, the sprite icons it replaces (`sheet icons`) and how well its",
        "poses cover them (silhouette IoU, min / mean). Converted by `tools/rd4_to_gltf/` and CNA's",
        "`tools/avatar_asset_pipeline/convert_avatar.py`; loaded from the listed directory. Sprites with",
        "no model here (effects, the charge 31, the shield 25) stay billboards by decision",
        "(`plans/GALAXY_EGGBERT_COMPLETION.md` §7).",
        "",
        "| Model directory | Source scene(s) | Parts | Clips | Replaces | IoU min / mean |",
        "|---|---|---|---|---|---|",
    ]
    directories = [AVATARS / "blupi"]
    vehicles = AVATARS / "blupi" / "vehicles"
    if vehicles.is_dir():
        directories += sorted(p for p in vehicles.iterdir() if p.is_dir())
    for name in (AVATARS / "objects" / "index.txt").read_text(encoding="utf-8").splitlines():
        if name and not name.startswith("#"):
            directories.append(AVATARS / "objects" / name)
    for directory in directories:
        row = model_row(directory, sources)
        if directory.name == "blupi":
            row["source"] = "Blupi/*.rd4 (geometry, skeleton, camera: Blupi/marche-profil.rd4)"
        elif directory.parent == vehicles:
            row["source"] = f"Blupi/*.rd4 (the {directory.name} scenes; tools/rd4_to_gltf/ README)"
        iou = f"{row['iou'][0]:.2f} / {row['iou'][1]:.2f}" if row["iou"] else "-"
        lines.append(f"| `{row['dir']}` | {row['source']} | {row['parts']} | {row['clips']} | "
                     f"{icon_summary(row['icons'])} | {iou} |")
    lines.append("")
    lines.append(f"{len(directories)} models.")
    lines.append("")
    return "\n".join(lines)


def main(argv) -> int:
    text = build()
    if len(argv) > 1 and argv[1] == "--check":
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"FAIL: {OUT.relative_to(ROOT)} is stale; rerun tools/asset_inventory.py")
            return 1
        print(f"PASS: {OUT.relative_to(ROOT)} matches the shipped models")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
