#!/usr/bin/env python3
"""The object models' parity matrix (plans/GALAXY_EGGBERT_COMPLETION.md §7.3, milestone C): every
model of avatars3d/objects/ with its Ray Dream source, the icons it draws and how well it matches
them (the silhouette IoU against each icon, from its icons.txt), and a verdict.

    python3 tools/model_parity.py > plans/inventory/model_parity.md

A model whose worst icon matches at 0.85 or better is faithful in silhouette; the weaker ones
carry the verdict found by looking at their compare sheets (build_object_library.py's
compare.png: sprite, model, overlap) and live. The silhouette does not measure colour: the
procedural textures are flatter than the sprites' (open, plan §7.3).
"""

from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
FAITHFUL = 0.85
# Verdicts for the models under FAITHFUL, from their compare sheets and live views.
NOTES = {
    "bird_oiseau": "faithful: its weakest icons are turning frames whose thin wings and legs land a "
                   "pixel off at 60 pixels (compare sheet; live in 084)",
    "bd_plante1a_plante1a": "faithful: thin leaf edges a pixel off; the trunk's bark is a flat texture",
    "bd_plante1b_plante1b": "faithful: thin leaf edges a pixel off; the trunk's bark is a flat texture",
    "bd_plante1c_plante1c": "faithful: thin leaf edges a pixel off; the trunk's bark is a flat texture",
    "bd_plante1d_plante1d": "faithful: thin leaf edges a pixel off; the trunk's bark is a flat texture",
    "bd_plante3a_plante3a": "faithful: thin leaves, and the sprite is cut at its icon's bottom edge",
    "bd_plante3b_plante3b": "faithful: thin leaves, and the sprite is cut at its icon's bottom edge",
    "bd_plante3c_plante3c": "faithful: thin leaves, and the sprite is cut at its icon's bottom edge",
    "fish_poisson": "its head is rounder and larger than the sprites' (BB3D-032, open)",
}


def main() -> int:
    rows = []
    for d in sorted((REPO / "avatars3d" / "objects").iterdir()):
        icons = d / "icons.txt"
        if not icons.exists():
            continue
        lines = icons.read_text().splitlines()
        source = lines[0].lstrip("# ").split(";")[0].split(": ", 1)[-1] if lines else ""
        ious = [float(line.split()[6]) for line in lines if line.startswith("icon ")]
        if not ious:
            continue
        worst = min(ious)
        verdict = NOTES.get(d.name, "faithful" if worst >= FAITHFUL else "to look at")
        rows.append((d.name, source, len(ious), sum(ious) / len(ious), worst, verdict))
    print("# Object model parity\n")
    print("Generated by `tools/model_parity.py` from `avatars3d/objects/*/icons.txt`: each model's Ray Dream")
    print("source, the sprite icons it draws, the silhouette IoU against them (mean, worst) and a verdict.")
    print("Colour is not measured: the procedural textures are flatter than the sprites' (open).\n")
    print("| Model | Source | Icons | IoU mean | IoU worst | Verdict |")
    print("|---|---|---|---|---|---|")
    for name, source, count, mean, worst, verdict in rows:
        print(f"| {name} | {source} | {count} | {mean:.3f} | {worst:.3f} | {verdict} |")
    weak = sum(1 for r in rows if r[4] < FAITHFUL)
    print(f"\n{len(rows)} models: {len(rows) - weak} match every icon at {FAITHFUL} or better; "
          f"{weak} below, each with its verdict.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
