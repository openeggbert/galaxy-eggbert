#!/usr/bin/env python3
"""The glue death's strands (element 168-171; owner 2026-11-04, Q-006: add them).

Blupi/glu.rd4 holds only Blupi: the strands of glue from his hands to the puddle and its peaks
round his feet were painted on the renders. This finds them in each sprite -- its thin green
texels outside his body (the sprite less a morphological opening of it) -- thins them to centre
lines (tools/bolt/bolt_paths.py's tracer) and writes src/GalaxyEggbert/Game/GlueStrands.hpp: per
frame, polylines in the glue model's space (64 sprite pixels a block, the icon's centre the origin,
y up) with the strand's half-width, and a texel of the strands' green (u, v in the icon).

    python3 tools/glue/glue_strands.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
from PIL import Image

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "tools" / "bolt"))
import bolt_paths as bp  # noqa: E402

ICONS = range(168, 172)
SIZE, COLS = 60, 10


def morph(m, grow):
    p = np.pad(m, 1)
    out = np.zeros_like(m) if grow else np.ones_like(m)
    for dy in (0, 1, 2):
        for dx in (0, 1, 2):
            win = p[dy:dy + m.shape[0], dx:dx + m.shape[1]]
            out = out | win if grow else out & win
    return out


def main() -> int:
    sheet = Image.open(REPO / "Content" / "icons" / "element.png").convert("RGBA")
    frames, texels = [], []
    for icon in ICONS:
        c, r = icon % COLS, icon // COLS
        t = np.asarray(sheet.crop((c * SIZE, r * SIZE, c * SIZE + SIZE, r * SIZE + SIZE))).astype(int)
        mask = t[:, :, 3] >= 128
        body = morph(morph(morph(morph(mask, False), False), True), True)
        green = (t[:, :, 1] > t[:, :, 0]) & (t[:, :, 1] > t[:, :, 2]) & (t[:, :, 1] > 40)
        strands = mask & ~morph(body, True) & green
        strands[:12, :] = False  # his antennae's tips, not glue
        ys, xs = np.nonzero(strands)
        texels.append(((xs.mean() + 0.5) / SIZE, (ys.mean() + 0.5) / SIZE) if len(xs) else (0.5, 0.9))
        # the strands' own darkest green texel, as their colour
        if len(xs):
            k = int(np.argmin(t[ys, xs, 1]))
            texels[-1] = ((xs[k] + 0.5) / SIZE, (ys[k] + 0.5) / SIZE)
        skel = bp.thin(strands)
        polylines = []
        for path in bp.trace(skel):
            simple = bp.rdp(path)
            # The painted strands are a texel or two wide: a tube of 0.9 px half-width.
            polylines.append([((x + 0.5 - SIZE / 2) / 64.0, (SIZE / 2 - y - 0.5) / 64.0, 0.9 / 64.0)
                              for y, x in simple])
        frames.append(polylines)
    lines = [
        "#pragma once",
        "",
        "// Generated by tools/glue/glue_strands.py from element.png's glue death frames 168-171: the",
        "// painted strands' centre lines in the glue model's space (64 px a block, the icon's centre the",
        "// origin, y up) with their half-width (Q-006).",
        "",
        "#include \"BoltPaths.hpp\"",
        "",
        "#include <array>",
        "",
        "namespace GalaxyEggbert::Game",
        "{",
    ]
    points, polys, ranges = [], [], []
    for polylines in frames:
        start = len(polys)
        for pl in polylines:
            polys.append((len(points), len(pl)))
            points.extend(pl)
        ranges.append((start, len(polys) - start))
    lines.append("    inline constexpr std::array<BoltPoint, %d> kGluePoints{{" % len(points))
    lines += ["        {%.4ff, %.4ff, %.4ff}," % p for p in points]
    lines.append("    }};")
    lines.append("    inline constexpr std::array<BoltPolyline, %d> kGluePolylines{{" % len(polys))
    lines += ["        {%d, %d}," % p for p in polys]
    lines.append("    }};")
    lines.append("    // Per frame (168-171): its first polyline and how many.")
    lines.append("    inline constexpr std::array<BoltPolyline, 4> kGlueFrames{{")
    lines += ["        {%d, %d}," % r for r in ranges]
    lines.append("    }};")
    lines.append("    // Per frame: a texel of the strands' green (u, v in the icon, v down).")
    lines.append("    inline constexpr std::array<std::array<float, 2>, 4> kGlueTexel{{")
    lines += ["        {%.4ff, %.4ff}," % tx for tx in texels]
    lines.append("    }};")
    lines.append("}")
    out = REPO / "src" / "GalaxyEggbert" / "Game" / "GlueStrands.hpp"
    out.write_text("\n".join(lines) + "\n")
    print("wrote", out, [n for _, n in ranges], "points", len(points))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
